#!/usr/bin/env bash
# Step 8b's runs (e23): PC-303, a bounded change, from its settled ticket to the rung.
# From week-3-start with the curated baseline spec and the ticket's decisions log and
# glossary (seed/): e14 writes the change, e17 codes it, e18 runs the sensors, e19 reviews
# it (Opus three times, Codex once), then triage.py auto writes each review's packet, whose
# "Merges without a person" row is the rung. Everything goes in runs/<case>/ (W3_RUNS_ROOT),
# apart from PC-301's runs.
#
#   ./run.sh                 the clean case, every step (about 1.5 hours)
#   ./run.sh score [case]    the packets and results-<case>.md again, from the stored runs
#   ./run.sh resume <gate> <round>   after a gate: the clone at <round>'s e21 (or e17), then e21 with
#                            the gate (prompts/e21-pc-303.txt), e18, the reviews and the score,
#                            in runs/clean/
#   ./run.sh rebase <round>  the clone at <round>'s newest code, over a base commit that holds
#                            the curated baseline spec (as a real repository would), then e18,
#                            the reviews and the score, in runs/clean/ (no author run)
#   E23_OPUS_RUNS=3 E23_CODEX_RUNS=1 ./run.sh
#
# A case folder that already holds runs is not redone; delete runs/<case>/ to redo it.
# Codex needs CODEX_API_KEY in this shell. At the end the clone holds PC-303's change.
set -uo pipefail
count() { local i=1; while [ "$i" -le "$1" ]; do echo "$i"; i=$((i + 1)); done; }  # 1..n; none for 0 (BSD seq 1 0 counts down)
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
exp="$(dirname "$here")"
week3="$exp"
W3_WORK="${W3_WORK:-$HOME/.cache/qcon-he/week3}"
export W3_WORK W3_TICKET=pc-303
work="$W3_WORK/petclinic"
opus="${E23_OPUS_RUNS:-3}"
codex="${E23_CODEX_RUNS:-1}"

newest() { find "$1" -mindepth 1 -maxdepth 1 -type d 2> /dev/null | sort | tail -1; }

score() {  # score <case>: one packet per review, and the table
  local case="$1" root="$here/runs/$1" s18 out
  s18="$(newest "$root/e18-run-the-sensors")"
  [ -n "$s18" ] && [ -f "$s18/sensors.md" ] || { echo "e23: no sensors run in $root" >&2; return 1; }
  out="$here/results-$case.md"
  mkdir -p "$root/packets"
  {
    echo "# Step 8b's results: $case"
    echo
    echo "Generated by \`run.sh score\` from \`runs/$case/\`: each review alone through the policy (\`triage.py auto\`), with the sensors of \`$(basename "$s18")\`. Check every row against its review and packet."
    echo
    echo "| Review | Merges without a person | Eligible to merge | Questions | Fixes | Findings |"
    echo "|---|---|---|---|---|---|"
    for r in $(find "$root/e19-review-the-code" -mindepth 1 -maxdepth 1 -type d 2> /dev/null | sort); do
      [ -f "$r/review.md" ] || continue
      local t; t="$(mktemp -d)"
      mkdir -p "$t/inputs"
      cp "$r/review.md" "$t/inputs/review-step6-x.md"
      cp "$s18/sensors.md" "$t/inputs/sensors.md"
      python3 -B "$week3/sensors/triage.py" auto "$t/inputs" > /dev/null 2>&1
      cp "$t/packet.md" "$root/packets/$(basename "$r").md"
      python3 - "$t/packet.md" "$(basename "$r")" <<'PY'
import re, sys
p, name = open(sys.argv[1], encoding="utf-8").read(), sys.argv[2]
row = lambda k: (re.search(r"^\| " + k + r" \| (.*?) \|$", p, re.M) or [None, "?"])[1]
q = len(re.findall(r"^\*\*T\d+\.", p, re.M))
f = len(re.findall(r"^- \*\*T\d+\*\* \(", p, re.M))
print(f"| {name.split('-', 2)[-1]} `{name[:15]}` | {row('Merges without a person')} | {row('Eligible to merge')} | {q} | {f} | {row('Findings')} |")
PY
      rm -rf "$t"
    done
    # All the reviews in one packet: no review alone can make the change look clean.
    local t; t="$(mktemp -d)"
    mkdir -p "$t/inputs"
    for r in $(find "$root/e19-review-the-code" -mindepth 1 -maxdepth 1 -type d 2> /dev/null | sort); do
      [ -f "$r/review.md" ] && cp "$r/review.md" "$t/inputs/review-step6-$(basename "$r").md"
    done
    cp "$s18/sensors.md" "$t/inputs/sensors.md"
    python3 -B "$week3/sensors/triage.py" auto "$t/inputs" > /dev/null 2>&1
    cp "$t/packet.md" "$root/packets/all-reviews.md"
    python3 - "$t/packet.md" "all four together" <<'PY'
import re, sys
p, name = open(sys.argv[1], encoding="utf-8").read(), sys.argv[2]
row = lambda k: (re.search(r"^\| " + k + r" \| (.*?) \|$", p, re.M) or [None, "?"])[1]
q = len(re.findall(r"^\*\*T\d+\.", p, re.M))
f = len(re.findall(r"^- \*\*T\d+\*\* \(", p, re.M))
print(f"| **{name}** | {row('Merges without a person')} | {row('Eligible to merge')} | {q} | {f} | {row('Findings')} |")
PY
    rm -rf "$t"
  } > "$out"
  cat "$out"
}

review() {  # review <root>: the sensors, the four reviews and the score, on the clone as it is
  local root="$1"
  echo "e23: e18, the sensors"
  ./demo.sh e18 > "$root/e18.out" 2>&1 || echo "e23: e18 exited with an error" >&2
  for i in $(count "$opus"); do
    echo "e23: e19, Opus review $i"
    LADDER_BATCH=1 ./demo.sh e19 > "$root/e19-opus-$i.out" 2>&1 || echo "e23: Opus review $i exited with an error" >&2
  done
  for i in $(count "$codex"); do
    echo "e23: e19, Codex review $i"
    LADDER_BATCH=1 LADDER_AGENT=codex ./demo.sh e19 > "$root/e19-codex-$i.out" 2>&1 || echo "e23: Codex review $i exited with an error" >&2
  done
  score "$(basename "$root")"
}

if [ "${1:-}" = score ]; then score "${2:-clean}"; exit; fi

case=clean
root="$here/runs/$case"
if [ -d "$root" ] && [ -n "$(ls -A "$root" 2> /dev/null)" ]; then
  echo "e23: runs/$case already has runs; move it aside (runs/clean-roundN) to redo, or ./run.sh score" >&2; exit 1
fi
if [ "$codex" != 0 ] && [ -z "${CODEX_API_KEY:-}" ]; then
  echo "e23: set CODEX_API_KEY for the Codex run, or E23_CODEX_RUNS=0" >&2; exit 1
fi
cd "$exp"
start="$(git -C "$work" rev-parse -q --verify "week-3-start^{commit}" 2> /dev/null || echo 76adfc4)"

base_commit() {  # the curated baseline spec, committed on week-3-start: the same hash every time
  local spec="$work/openspec/specs/pets/spec.md" keep
  keep="$(mktemp)"
  cp "$spec" "$keep"
  cp "$week3/baseline/pets-spec.md" "$spec"
  git -C "$work" add openspec/specs/pets/spec.md
  GIT_AUTHOR_DATE="2026-11-02T00:00:00Z" GIT_COMMITTER_DATE="2026-11-02T00:00:00Z" \
    git -C "$work" -c user.name="Week 3 harness" -c user.email="harness@example.invalid" \
      commit --quiet -m "The baseline spec of the pet forms, curated (baseline/pets-spec.md)"
  cp "$keep" "$spec"
  rm -f "$keep"
  echo "e23: base commit $(git -C "$work" log --oneline -1)"
}

if [ "${1:-}" = rebase ]; then
  from="${2:-}"
  [ -n "$from" ] || { echo "usage: ./run.sh rebase <round folder in runs/>" >&2; exit 2; }
  step=e17; [ -d "$here/runs/$from/e21-fix-the-findings" ] && step=e21
  W3_RUNS_ROOT="$here/runs/$from" ./demo.sh apply $step || exit 1
  [ "$(git -C "$work" rev-parse HEAD)" = "$(git -C "$work" rev-parse "$start")" ] || { echo "e23: the clone is not on week-3-start" >&2; exit 1; }
  base_commit || exit 1
  echo "e23: the change against the base: $(git -C "$work" status --porcelain | wc -l | tr -d ' ') changed files; the spec: $(git -C "$work" diff --numstat -- openspec/specs/pets/spec.md)"
  mkdir -p "$root"
  export W3_RUNS_ROOT="$root"
  review "$root"
  exit
fi

if [ "${1:-}" = resume ]; then
  gate="${2:-}"; from="${3:-}"
  [ -n "$gate" ] && [ -n "$from" ] || { echo "usage: ./run.sh resume <gate> <round folder in runs/>" >&2; exit 2; }
  case "$gate" in /*) ;; *) gate="$here/$gate" ;; esac
  [ -f "$gate" ] || { echo "e23: no gate $gate" >&2; exit 1; }
  # The newest code of that round: its e21 run if it had one, else its e17 run.
  step=e17; [ -d "$here/runs/$from/e21-fix-the-findings" ] && step=e21
  [ -d "$here/runs/$from/$( [ $step = e21 ] && echo e21-fix-the-findings || echo e17-code-the-change)" ] || { echo "e23: runs/$from has no e17 or e21 run" >&2; exit 1; }
  W3_RUNS_ROOT="$here/runs/$from" ./demo.sh apply $step || exit 1
  mkdir -p "$root"
  export W3_RUNS_ROOT="$root"
  echo "e23: e21 works through $(basename "$gate")"
  W3_GATE="$gate" LADDER_BATCH=1 ./demo.sh e21 > "$root/e21.out" 2>&1 || echo "e23: e21 exited with an error" >&2
  review "$root"
  exit
fi
[ -d "$work/.git" ] || ./demo.sh reset || exit 1
# The base: week-3-start, the curated baseline spec, the ticket's decisions log and glossary.
git -C "$work" checkout --quiet -- . && git -C "$work" clean -fdq || exit 1
start="$(git -C "$work" rev-parse -q --verify "week-3-start^{commit}" 2> /dev/null || echo 76adfc4)"
git -C "$work" -c advice.detachedHead=false checkout --quiet "$start" || exit 1
./demo.sh baseline || exit 1
mkdir -p "$work/openspec/changes/pc-303"
cp "$here/seed/decisions.md" "$work/openspec/changes/pc-303/decisions.md"
cp "$here/seed/GLOSSARY.md" "$work/GLOSSARY.md"
echo "e23: base at $(git -C "$work" log --oneline -1), with the baseline spec and PC-303's decisions log"
mkdir -p "$root"
export W3_RUNS_ROOT="$root"
echo "e23: e14 writes the change"
LADDER_BATCH=1 ./demo.sh e14 > "$root/e14.out" 2>&1 || echo "e23: e14 exited with an error" >&2
[ -f "$work/openspec/changes/pc-303/tasks.md" ] || { echo "e23: e14 wrote no tasks.md; see $root/e14.out" >&2; exit 1; }
echo "e23: e17 codes it"
LADDER_BATCH=1 ./demo.sh e17 > "$root/e17.out" 2>&1 || echo "e23: e17 exited with an error" >&2
[ -n "$(git -C "$work" status --porcelain -- src)" ] || { echo "e23: e17 changed no code; see $root/e17.out" >&2; exit 1; }
review "$root"
