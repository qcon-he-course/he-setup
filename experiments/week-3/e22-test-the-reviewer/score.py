#!/usr/bin/env python3
"""score: step 8's results, from e22's runs and the case catalogue.

  score.py <e22 folder>

For each case in cases/cases.json and each review in runs/<case>/e19-review-the-code/:
caught (a BLOCK or DISCUSS finding names the flaw), seen (only an AUTO-FIX or
INFORMATIONAL finding names it) or missed; whether a sensor caught it (from the case's
sensors.md); and the packet the policy writes for that review alone (triage.py auto):
eligible or not, and how many questions reach the person. Also the false METs on the two
scenarios no test shows ("Three errors on the add form", "Two errors on the edit form").
Writes results.md and prints it. The scorer reads words only: check every row against the
review before it goes on a slide.
"""

import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "sensors"))
import triage  # noqa: E402
UNTESTED = ["Three errors on the add form", "Two errors on the edit form"]


def findings(text):
    """[(id, disposition, text of the finding)], read the way the policy reads them (triage.py),
    so the score and the packet cannot disagree about what a review said."""
    return [(f["id"], (f["disposition"] or "UNREADABLE").replace("AUTO-FIX+REVERIFY", "AUTO-FIX"), f["text"])
            for f in triage.finding_blocks(text)]


def false_mets(text):
    n = 0
    for t in UNTESTED:
        for line in text.splitlines():
            if line.startswith("|") and re.search(r"\|\s*" + re.escape(t) + r"(\s*\(unchanged\))?\s*\|", line) and re.search(r"\|\s*\**MET\**\s*\|", line):
                n += 1
                break
    return n


def packet(review, sensors, triage):
    d = tempfile.mkdtemp()
    try:
        os.makedirs(os.path.join(d, "inputs"))
        shutil.copy(review, os.path.join(d, "inputs", "review-step6-x.md"))
        shutil.copy(sensors, os.path.join(d, "inputs", "sensors.md"))
        subprocess.run([sys.executable, "-B", triage, "auto", os.path.join(d, "inputs")], capture_output=True)
        p = open(os.path.join(d, "packet.md"), encoding="utf-8").read()
        elig = re.search(r"^\| Eligible to merge \| \*\*(\w+)", p, re.M)
        qs = len(re.findall(r"^\*\*T\d+\.", p, re.M))
        return (elig.group(1) if elig else "?"), qs
    finally:
        shutil.rmtree(d)


def newest(d):
    xs = sorted(x for x in os.listdir(d) if os.path.isdir(os.path.join(d, x))) if os.path.isdir(d) else []
    return os.path.join(d, xs[-1]) if xs else None


def run(e22):
    cases = json.load(open(os.path.join(e22, "cases", "cases.json")))
    triage = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "sensors", "triage.py")
    L = ["# Step 8's results", "", "Generated by `score.py` from `runs/`. Caught: a BLOCK or DISCUSS finding names the flaw. Seen: only an AUTO-FIX or INFORMATIONAL finding does. Packet: the policy on that review alone (`triage.py auto`). Check every row against the review.", "",
         "| Case | Sensor caught it | Review | Result | Finding | Packet | Questions | False METs |", "|---|---|---|---|---|---|---|---|"]
    summary = {}
    for case, spec in cases.items():
        root = os.path.join(e22, "runs", case)
        s18 = newest(os.path.join(root, "e18-run-the-sensors"))
        sensors = os.path.join(s18, "sensors.md") if s18 else None
        stext = open(sensors, encoding="utf-8").read() if sensors and os.path.exists(sensors) else ""
        sensor = "yes" if spec["sensor"] and any(re.search(p, stext) for p in spec["sensor"]) else ("-" if not spec["sensor"] else "no")
        if not stext:
            sensor = "no run"
        rdir = os.path.join(root, "e19-review-the-code")
        reviews = sorted(x for x in os.listdir(rdir)) if os.path.isdir(rdir) else []
        if not reviews:
            L.append(f"| {case} | {sensor} | no review run | | | | | |")
            continue
        for r in reviews:
            rv = os.path.join(rdir, r, "review.md")
            text = open(rv, encoding="utf-8").read() if os.path.exists(rv) else ""
            model = r.split("-", 2)[-1]
            fs = findings(text)
            hit = [(i, d) for i, d, t in fs if spec["reviewer"] and any(re.search(p, t, re.I) for p in spec["reviewer"])]
            if not spec["reviewer"]:
                blocks = [i for i, d, t in fs if d == "BLOCK"]
                result, where = (f"{len(blocks)} BLOCK" if blocks else "no BLOCK"), ", ".join(blocks)
            elif any(d in ("BLOCK", "DISCUSS") for _, d in hit):
                result, where = "caught", ", ".join(f"{i} {d}" for i, d in hit)
            elif hit:
                result, where = "seen", ", ".join(f"{i} {d}" for i, d in hit)
            else:
                result, where = "missed", ""
            elig, qs = packet(rv, sensors, triage) if text and sensors and os.path.exists(sensors) else ("?", 0)
            L.append(f"| {case} | {sensor} | {model} `{r[:15]}` | {result} | {where} | {elig} | {qs} | {false_mets(text)} |")
            summary.setdefault(case, []).append((model, result))
    L += ["", "## Per case", "", "| Case | Opus | Codex | Runs that agree |", "|---|---|---|---|"]
    for case, rs in summary.items():
        o = [r for m, r in rs if m.startswith("claude")]
        c = [r for m, r in rs if not m.startswith("claude")]
        if not cases[case]["reviewer"]:  # the clean case: runs with a false BLOCK
            fmt = lambda xs: (f"{sum(1 for x in xs if x != 'no BLOCK')} of {len(xs)} with a BLOCK") if xs else "-"
        else:
            fmt = lambda xs: f"{sum(1 for x in xs if x == 'caught')} of {len(xs)}" if xs else "-"
        agree = "all" if len(set(r for _, r in rs)) == 1 else "split: " + ", ".join(sorted(set(r for _, r in rs)))
        L.append(f"| {case} | {fmt(o)} | {fmt(c)} | {agree} |")
    out = "\n".join(L) + "\n"
    open(os.path.join(e22, "results.md"), "w", encoding="utf-8").write(out)
    print(out)
    return 0


if __name__ == "__main__":
    sys.exit(run(sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))))
